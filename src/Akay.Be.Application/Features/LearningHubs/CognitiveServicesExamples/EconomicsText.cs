        es el coste de oportunidad: el valor de la mejor alternativa a la que se
        renuncia al tomar una decision. Cada eleccion implica un sacrificio, y entender
        este concepto ayuda a evaluar si las decisiones son eficientes. La economia
        tambien nos proporciona herramientas para analizar problemas reales, como la
        desigualdad, el cambio climatico o las crisis financieras, permitiendo disenar
        politicas que mejoren el bienestar social.
