-- Review and apply manually to the intended database. No migrations or existing-data changes.
-- This script deliberately fails if the table already exists rather than hiding schema drift.
BEGIN;

CREATE SCHEMA IF NOT EXISTS notification;

CREATE TABLE notification.notification (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id integer NOT NULL,
    type text NOT NULL,
    title text NOT NULL,
    message text NOT NULL,
    url text NULL,
    payload jsonb NULL,
    created_at timestamp with time zone NOT NULL,
    read_at timestamp with time zone NULL,
    CONSTRAINT "PK_notifications" PRIMARY KEY (id)
);

CREATE INDEX "IX_Notification_UserId_CreatedAt"
    ON notification.notification (user_id, created_at DESC, id DESC);

CREATE INDEX "IX_Notification_UserId_Unread"
    ON notification.notification (user_id, created_at DESC)
    WHERE read_at IS NULL;

COMMIT;
